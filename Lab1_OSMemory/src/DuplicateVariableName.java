/**
* exception for when 2 variables share the same name
*/
public class DuplicateVariableName extends Exception
{
	/**
	 * exception for when 2 variables share the same name
	 */
	public DuplicateVariableName()
	{
	}
	
	/**
	 * exception for when 2 variables share the same name
	 */
	public DuplicateVariableName(String message)
	{
		super(message);
	}
}