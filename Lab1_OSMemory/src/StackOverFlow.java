/**
 * thrown when the the memory that is wanted to be added to the stack exceeds the size of the stack
 */
public class StackOverFlow extends Exception
{
	/**
	 * thrown when the the memory that is wanted to be added to the stack exceeds the size of the stack
	 */
	public StackOverFlow()
	{
	}
	
	/**
	 * thrown when the the memory that is wanted to be added to the stack exceeds the size of the stack
	 */
	public StackOverFlow(String message)
	{
		super(message);
	}

}
